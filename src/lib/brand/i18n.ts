// i18n / locale-pack emission. Emits public/locales/<locale>/common.json for
// each requested locale, plus a minimal src/i18n.ts i18next bootstrap. RTL
// locales (ar, he, fa, ur) trigger a global CSS rule targeting html[dir="rtl"].

import fs from 'node:fs/promises'
import { dirname, join } from 'node:path'

import { ensureDir } from '../fs.js'

import type { BrandKit } from './index.js'

export const RTL_LOCALES = new Set(['ar', 'he', 'fa', 'ur'])

export type LocalePack = Record<string, string>

export function isRtl(locale: string): boolean {
  return RTL_LOCALES.has(locale.split('-')[0].toLowerCase())
}

